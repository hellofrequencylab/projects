#!/usr/bin/env node
// Regenerates apps/ui/cyber_icons.h from build_icons.js for the firmware.
//
//   node design/icons/gen_firmware.js [--preview out.png]
//
// Same palette and index scheme as generate.js (the design tool's version),
// but run-length packed so the whole set costs a few KB of flash instead of
// 768 bytes per icon, and keyed by the Bruce menu name so the skin can find an
// icon for any menu item without touching the app. Only icons for menu items
// that exist are emitted: add or drop a line in MENU below.
'use strict';
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const here = __dirname;
const src = fs.readFileSync(path.join(here, 'build_icons.js'), 'utf8');
const { buildIcons } = new Function('module', src + '\nreturn module.exports;')({ exports: {} });
const { W, H, PALETTE, icons } = buildIcons();

// icon id -> menu name (MenuItemInterface("...")), in main-menu order.
// The label shown on screen is the icon's name from build_icons.js.
const MENU = [
  ['frequency', 'Frequency'],
  ['sensors', 'Sensors'],
  ['light', 'Light'],
  ['sound', 'Sound'],
  ['slideshow', 'Slideshow'],
  ['weather', 'Weather'],
  ['hat', 'Hat'],
  ['gpio', 'GPIO'],
  ['remote', 'Remote'],
  ['library', 'Library'],
  ['spectrum', 'Spectrum'],
  ['wifi', 'WiFi'],
  ['ble', 'BLE'],
  ['rf', 'RF'],
  ['nrf24', 'NRF24'],
  ['ir', 'IR'],
  ['gps', 'GPS'],
  ['rfid', 'RFID'],
  ['files', 'Files'],
  ['scripts', 'JS Interpreter'],
  ['clock', 'Clock'],
  ['others', 'Others'],
  ['config', 'Config'],
];

const keys = PALETTE.map(p => p[0]);
if (keys.length > 32) throw new Error('palette must fit 5 bits');
const rgb565 = ([r, g, b]) => ((r & 0xf8) << 8) | ((g & 0xfc) << 3) | (b >> 3);
const modeC = { row: 'CYI_ROW', col: 'CYI_COL', diag: 'CYI_DIAG', angle: 'CYI_ANGLE' };

// Byte = (run-1) << 5 | index for runs of 1-7; top bits 111 = long run, the
// next byte holds run-8 (8-263).
function pack(grid) {
  const cells = grid.join('').split('').map(c => keys.indexOf(c));
  const out = [];
  for (let i = 0; i < cells.length;) {
    let n = 1;
    while (i + n < cells.length && cells[i + n] === cells[i] && n < 263) n++;
    if (n <= 7) out.push(((n - 1) << 5) | cells[i]);
    else out.push((7 << 5) | cells[i], n - 8);
    i += n;
  }
  return out;
}

let blob = [], table = [];
for (const [id, menu] of MENU) {
  const ic = icons[id];
  if (!ic) throw new Error('no icon ' + id);
  table.push({ id, menu, label: ic.name, mode: ic.mode, off: blob.length });
  blob = blob.concat(pack(ic.grid));
}
if (blob.length > 65535) throw new Error('offsets are 16 bit');

let h = '// Generated by design/icons/gen_firmware.js from design/icons/build_icons.js. Do not edit.\n';
h += '// CyberUnicorn 5000 app icons: 32x24 palette-indexed pixel art, run-length packed.\n';
h += '// Included once, by cyber_icon.cpp.\n#pragma once\n#include <stdint.h>\n\n';
h += `#define CYI_W ${W}\n#define CYI_H ${H}\n#define CYI_COUNT ${table.length}\n`;
h += '#define CYI_TRANSPARENT 0\n#define CYI_RAINBOW 1\n';
h += `#define CYI_SPARKLE ${keys.indexOf('S')}\n#define CYI_FRAME_A ${keys.indexOf('A')}\n#define CYI_FRAME_B ${keys.indexOf('a')}\n`;
h += `#define CYI_FLOOR ${keys.indexOf('N')}\n#define CYI_GRID_A ${keys.indexOf('Q')}\n#define CYI_GRID_B ${keys.indexOf('q')}\n\n`;
h += 'enum CyberIconMode : uint8_t { CYI_ROW, CYI_COL, CYI_DIAG, CYI_ANGLE };\n\n';
h += '// RGB565 per index; rainbow, sparkle and frame A/B are computed (0 here).\n';
h += `static const uint16_t cyi_palette[${PALETTE.length}] = {\n`;
h += PALETTE.map(([k, v, d]) => `    0x${(Array.isArray(v) ? rgb565(v) : v === 'gridA' || v === 'gridB' ? rgb565([0, 160, 255]) : 0).toString(16).toUpperCase().padStart(4, '0')}, // ${k} ${d}`).join('\n') + '\n};\n\n';
h += `// ${blob.length} bytes for ${table.length} icons (${table.length * W * H} unpacked).\n`;
h += `static const uint8_t cyi_rle[${blob.length}] = {\n`;
for (let i = 0; i < blob.length; i += 24) h += '    ' + blob.slice(i, i + 24).join(',') + ',\n';
h += '};\n\n';
h += 'struct CyberIcon {\n    const char *menu;  // MenuItemInterface name\n    const char *label; // shown under the icon\n    uint8_t mode;\n    uint16_t off;      // into cyi_rle\n};\n\n';
h += 'static const CyberIcon cyi_icons[CYI_COUNT] = {\n';
h += table.map(t => `    {"${t.menu}", "${t.label}", ${modeC[t.mode]}, ${t.off}}, // ${t.id}`).join('\n') + '\n};\n';

const out = path.join(here, '..', '..', 'apps', 'ui', 'cyber_icons.h');
fs.writeFileSync(out, h);
console.log(`${path.relative(process.cwd(), out)}: ${table.length} icons, ${blob.length} bytes packed`);

// Optional preview sheet: frame A (top) and B (bottom), 4 px per cell.
const pi = process.argv.indexOf('--preview');
if (pi > 0) {
  const hue = h0 => { const x = ((h0 % 360) + 360) % 360, s = Math.floor(x / 60), f = (x % 60) * 255 / 60; return [[255, f, 0], [255 - f, 255, 0], [0, 255, f], [0, 255 - f, 255], [f, 0, 255], [255, 0, 255 - f]][s]; };
  const base = (m, x, y) => m === 'row' ? y * 18 : m === 'col' ? x * 12 : m === 'diag' ? (x + y) * 10 : Math.atan2(y - 11.5, x - 15.5) * 180 / Math.PI + 180;
  const pal = Object.fromEntries(PALETTE.map(([k, v]) => [k, v]));
  const S = 4, cw = W * S + 16, ch = H * S + 16, cols = 6, rows = Math.ceil(table.length / cols);
  const PW = cw * cols, PH = ch * rows * 2, px = Buffer.alloc(PW * PH * 3);
  for (let fr = 0; fr < 2; fr++) table.forEach((t, i) => {
    const ic = icons[t.id], ox = (i % cols) * cw + 8, oy = (Math.floor(i / cols) + fr * rows) * ch + 8;
    ic.grid.forEach((row, y) => [...row].forEach((k, x) => {
      let v = pal[k];
      if (v === null) return;
      if (v === 'gridA') v = fr ? [12, 0, 28] : [0, 160, 255];
      if (v === 'gridB') v = fr ? [0, 160, 255] : [12, 0, 28];
      if ((v === 'frameA' && fr) || (v === 'frameB' && !fr)) return;
      if (v === 'rainbow' || v === 'frameA' || v === 'frameB') v = hue(base(ic.mode, x, y) + fr * 72);
      if (v === 'sparkle') { const p = (x * 3 + y * 5 + fr) % 6; if (p > 2) return; v = [[255, 255, 255], [0, 255, 255], [255, 90, 200]][p]; }
      for (let dy = 0; dy < S; dy++) for (let dx = 0; dx < S; dx++) {
        const o = ((oy + y * S + dy) * PW + ox + x * S + dx) * 3;
        px[o] = v[0]; px[o + 1] = v[1]; px[o + 2] = v[2];
      }
    }));
  });
  const raw = Buffer.alloc((PW * 3 + 1) * PH);
  for (let y = 0; y < PH; y++) px.copy(raw, y * (PW * 3 + 1) + 1, y * PW * 3, (y + 1) * PW * 3);
  const crcT = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
  const crc = b => { let c = 0xffffffff; for (const x of b) c = crcT[(c ^ x) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
  const chunk = (type, data) => { const l = Buffer.alloc(4); l.writeUInt32BE(data.length); const td = Buffer.concat([Buffer.from(type), data]); const c = Buffer.alloc(4); c.writeUInt32BE(crc(td)); return Buffer.concat([l, td, c]); };
  const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(PW, 0); ihdr.writeUInt32BE(PH, 4); ihdr[8] = 8; ihdr[9] = 2;
  fs.writeFileSync(process.argv[pi + 1], Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]));
}
